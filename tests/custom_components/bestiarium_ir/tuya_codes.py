"""The home's reference IR codes and the Tuya/Zosung decompression for tests."""

from __future__ import annotations

import base64
import json
import struct
from pathlib import Path
from typing import Any

LITERAL_LIMIT = 32
LONG_MATCH = 7


def decode_code(code: str) -> list[int]:
    """Return the unsigned timings of a Tuya/Zosung code."""
    data = base64.b64decode(code)
    out = bytearray()
    i = 0
    while i < len(data):
        head = data[i]
        i += 1
        if head < LITERAL_LIMIT:
            out += data[i : i + head + 1]
            i += head + 1
            continue
        length = head >> 5
        if length == LONG_MATCH:
            length += data[i]
            i += 1
        distance = ((head & 0x1F) << 8 | data[i]) + 1
        i += 1
        for _ in range(length + 2):
            out.append(out[-distance])
    return list(struct.unpack(f"<{len(out) // 2}H", out))


def load_vectors() -> dict[str, Any]:
    """
    Return the reference codes.

    "learned": codes learned from the real remote DG11R2-01; "home": the codes
    of the home's packages, generated by kelon_gen.py and working through a
    TS1201 (heat, cool, the display button of each, 16-30 °C, and "off").
    """
    return json.loads((Path(__file__).parent / "vectors.json").read_text())


def all_home_codes(vectors: dict[str, Any]) -> list[str]:
    """Return every code of the home's packages."""
    home = vectors["home"]
    return [home["off"]] + [
        code for key, codes in home.items() if key != "off" for code in codes.values()
    ]
